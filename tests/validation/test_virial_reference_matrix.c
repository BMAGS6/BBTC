/**
 * @file test_virial_reference_matrix.c
 * @brief VV0.1-B2b.3a independent mathematical reference matrix.
 *
 * @details
 * This developer-only cmocka test is the FIRST executable reference-runner
 * foundation for the accepted B2a cases M-01 through M-04. Each case is
 * executed once in each native scalar family. Its three independently known
 * mathematical values are passed to the already accepted B1 EXACT comparator,
 * alongside observations obtained exclusively through the B2 adapter.
 *
 * Mathematical oracle (NOT production Clenshaw):
 *
 *   x = 2 * (T - 256 K) / (512 K - 256 K) - 1
 *   s = 2 / (512 K - 256 K) = 2^-7 K^-1
 *   T0(x) = 1, T1(x) = x, T2(x) = 2*x*x - 1
 *   B      = c0 + c1*x + c2*(2*x*x - 1)
 *   dB/dT  = s*(c1 + 4*c2*x)
 *   d2B/dT2 = 4*c2*s*s
 *
 * M-01: c0=0; at T=384 K, B=0, dB/dT=0, d2B/dT2=0.
 * M-02: c0=2^-10, c1=2^-12; at T=384 K (x=0):
 *       B=2^-10, dB/dT=2^-19, d2B/dT2=0.
 * M-03: c2=2^-12; at T=384 K (x=0):
 *       B=-2^-12, dB/dT=0, d2B/dT2=2^-24.
 * M-04: c2=2^-12; at T=320 K (x=-1/2):
 *       B=-2^-13, dB/dT=-2^-18, d2B/dT2=2^-24.
 *
 * All coefficients and B are in m^3/kg; derivatives add K^-1 and K^-2.
 * The expected numbers are *literals justified by polynomial identities*;
 * they are not generated by the production evaluator or its recurrence.
 * The three precision families have separate, typed fixture and result
 * storage. No observation or expected value is routed through binary64.
 *
 * Every observation retains raw BBTC status and validity. Every numerical
 * quantity retains its distinct B1 operation status and finding. A missing
 * reference, failed producer invocation, or failed comparison cannot be
 * manufactured into a passing mathematical result. The test counts all
 * 4*3*3=36 decisions and fails if any is unexecuted or fails.
 *
 * ENVIRONMENT LIMIT: Basic host metadata, binary radix and current rounding
 * mode are screened here. This is not the full source-level/compiler/fenv
 * EXACT qualification required for B2b-wide scientific acceptance. Those
 * controls, plus deliberately wrong references and adversarial fixture
 * integrity checks, remain B2b.3b/3c obligations. Accordingly a passing test
 * is implementation-verification evidence, NOT physical model validation,
 * ammunition safety certification, or a B2b milestone acceptance decision.
 *
 * @see docs/validation/VVUQ_REFERENCE_ADAPTER_DESIGN_CONTRACT.md, sections 4-9
 */

