/**
 * @brief Execute one float mathematical reference without inventing an outcome.
 *
 * @details
 * This runner validates its bounded fixture identity before contacting
 * production. Its actual outputs come solely from the B2 adapter; its
 * expected outputs come solely from the polynomial identities above. All
 * three B1 EXACT comparisons have native zero tolerance and separate result
 * storage. Invalid production observations are NEVER passed to B1.
 *
 * @param index Index of a required M-01 through M-04 reference record.
 * @param profile_screened Whether basic ABI/rounding checks succeeded.
 * @param fixture Valid in-process fixture, possibly deliberately mutated by a self-test.
 * @param out Caller-owned complete, typed evidence; cleared on entry.
 */
static void run_reference_float(
    size_t index,
    bool profile_screened,
    const bbtc_vv_reference_fixture_float_t* fixture,
    bbtc_vv_reference_evidence_float_t* out
)
{
    if (out == NULL)
        return;

    *out = (bbtc_vv_reference_evidence_float_t){0};

    if (index >= BBTC_VV_REFERENCE_CASES || fixture == NULL)
    {
        out->common.integrity = BBTC_VV_REFERENCE_INTEGRITY_INVALID;
        return;
    }

    const bbtc_vv_case_metadata_t* metadata = fixture->metadata;
    out->common.precision = BBTC_PRECISION_FLOAT;
    out->common.profile = profile_screened
        ? BBTC_VV_REFERENCE_PROFILE_SCREENED_UNQUALIFIED
        : BBTC_VV_REFERENCE_PROFILE_UNSUPPORTED;

    if (!validate_case_metadata(index, metadata) ||
        fixture->coefficients == NULL ||
        fixture->coefficient_count != metadata->coefficient_count ||
        fixture->expected_present_mask != 0x07u ||
        !validate_quantity_metadata(fixture->quantities) ||
        !isfinite(fixture->expected[0]) ||
        !isfinite(fixture->expected[1]) ||
        !isfinite(fixture->expected[2]))
    {
        out->common.integrity = BBTC_VV_REFERENCE_INTEGRITY_INVALID;
        return;
    }

    out->common.id = metadata->id;
    out->common.revision = metadata->revision;
    out->common.required = metadata->required;
    out->common.category = metadata->category;
    out->common.integrity = BBTC_VV_REFERENCE_INTEGRITY_ACCEPTED;

    for (size_t q = 0u; q < BBTC_VV_REFERENCE_QUANTITIES; ++q)
    {
        out->expected[q] = fixture->expected[q];
        out->tolerances[q] = 0.0f;
        out->common.fields[q].quantity = fixture->quantities[q].quantity;
        out->common.fields[q].unit = fixture->quantities[q].unit;
        out->common.fields[q].method = BBTC_VV_COMPARISON_EXACT;
    }

    /* A screened profile is NOT marked qualified: that review is deferred. */
    if (!profile_screened)
        return;

    const bbtc_ib_first_order_virial_temperature_law_float_t law =
    {
        .minimum_temperature_k = 256.0f,
        .maximum_temperature_k = 512.0f,
        .second_density_virial_chebyshev_coefficients_m3_per_kg = fixture->coefficients,
        .coefficient_count = fixture->coefficient_count
    };
    bbtc_ib_first_order_virial_temperature_terms_float_t terms = {0};
    bool terms_valid = false;

    out->common.producer_called = true;
    out->common.producer_status = bbtc_vv_virial_observe_float(
        &law, fixture->temperature_k, &terms, &terms_valid);
    out->common.observation_valid = terms_valid;

    /* Raw production failure does not equal a numerical comparison FAIL. */
    if (out->common.producer_status != BBTC_STATUS_SUCCESS || !terms_valid)
        return;

    out->observed[0] = terms.second_density_virial_coefficient_m3_per_kg;
    out->observed[1] = terms.first_temperature_derivative_m3_per_kg_k;
    out->observed[2] = terms.second_temperature_derivative_m3_per_kg_k2;

    /* The comparator, not equality operators or rounded metrics, decides. */
    for (size_t q = 0u; q < BBTC_VV_REFERENCE_QUANTITIES; ++q)
    {
        const bbtc_vv_policy_float_t policy =
        {
            .method = BBTC_VV_COMPARISON_EXACT,
            .tolerance = out->tolerances[q]
        };
        bbtc_vv_result_float_t comparison = {0};

        out->common.fields[q].attempted = true;
        out->common.fields[q].operation_status = bbtc_vv_compare_float(
            out->expected[q], out->observed[q], &policy, &comparison);

        if (out->common.fields[q].operation_status == BBTC_VV_STATUS_SUCCESS)
            out->common.fields[q].finding = comparison.finding;
    }
}

