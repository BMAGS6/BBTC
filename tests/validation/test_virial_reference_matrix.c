/**
 * @brief Execute one long_double mathematical reference without inventing an outcome.
 *
 * @details
 * This runner validates its bounded fixture identity before contacting
 * production. Its actual outputs come solely from the B2 adapter; its
 * expected outputs come solely from the polynomial identities above. All
 * three B1 EXACT comparisons have native zero tolerance and separate result
 * storage. Invalid production observations are NEVER passed to B1.
 *
 * @param index Index of a required M-01 through M-04 reference record.
 * @param profile_screened Whether basic ABI/rounding checks succeeded.
 * @param out Caller-owned complete, typed evidence; cleared on entry.
 */
static void run_reference_long_double(
    size_t index,
    bool profile_screened,
    bbtc_vv_reference_evidence_long_double_t* out
)
{
    if (out == NULL)
        return;

    *out = (bbtc_vv_reference_evidence_long_double_t){0};

    if (index >= BBTC_VV_REFERENCE_CASES)
    {
        out->common.integrity = BBTC_VV_REFERENCE_INTEGRITY_INVALID;
        return;
    }

    const bbtc_vv_reference_fixture_long_double_t* fixture = &s_long_double_fixtures[index];
    const bbtc_vv_case_metadata_t* metadata = fixture->metadata;
    out->common.precision = BBTC_PRECISION_LONG_DOUBLE;
    out->common.profile = profile_screened
        ? BBTC_VV_REFERENCE_PROFILE_SCREENED_UNQUALIFIED
        : BBTC_VV_REFERENCE_PROFILE_UNSUPPORTED;

    if (!validate_case_metadata(index, metadata) ||
        fixture->coefficients == NULL ||
        fixture->coefficient_count != metadata->coefficient_count ||
        fixture->expected_present_mask != 0x07u)
    {
        out->common.integrity = BBTC_VV_REFERENCE_INTEGRITY_INVALID;
        return;
    }

    out->common.id = metadata->id;
    out->common.revision = metadata->revision;
    out->common.required = metadata->required;
    out->common.category = metadata->category;
    out->common.integrity = BBTC_VV_REFERENCE_INTEGRITY_ACCEPTED;

    for (size_t q = 0u; q < BBTC_VV_REFERENCE_QUANTITIES; ++q)
    {
        out->expected[q] = fixture->expected[q];
        out->tolerances[q] = 0.0L;
        out->common.fields[q].quantity = s_quantity_metadata[q].quantity;
        out->common.fields[q].unit = s_quantity_metadata[q].unit;
        out->common.fields[q].method = BBTC_VV_COMPARISON_EXACT;
    }

    /* A screened profile is NOT marked qualified: that review is deferred. */
    if (!profile_screened)
        return;

    const bbtc_ib_first_order_virial_temperature_law_long_double_t law =
    {
        .minimum_temperature_k = 256.0L,
        .maximum_temperature_k = 512.0L,
        .second_density_virial_chebyshev_coefficients_m3_per_kg = fixture->coefficients,
        .coefficient_count = fixture->coefficient_count
    };
    bbtc_ib_first_order_virial_temperature_terms_long_double_t terms = {0};
    bool terms_valid = false;

    out->common.producer_called = true;
    out->common.producer_status = bbtc_vv_virial_observe_long_double(
        &law, fixture->temperature_k, &terms, &terms_valid);
    out->common.observation_valid = terms_valid;

    /* Raw production failure does not equal a numerical comparison FAIL. */
    if (out->common.producer_status != BBTC_STATUS_SUCCESS || !terms_valid)
        return;

    out->observed[0] = terms.second_density_virial_coefficient_m3_per_kg;
    out->observed[1] = terms.first_temperature_derivative_m3_per_kg_k;
    out->observed[2] = terms.second_temperature_derivative_m3_per_kg_k2;

    /* The comparator, not equality operators or rounded metrics, decides. */
    for (size_t q = 0u; q < BBTC_VV_REFERENCE_QUANTITIES; ++q)
    {
        const bbtc_vv_policy_long_double_t policy =
        {
            .method = BBTC_VV_COMPARISON_EXACT,
            .tolerance = out->tolerances[q]
        };
        bbtc_vv_result_long_double_t comparison = {0};

        out->common.fields[q].attempted = true;
        out->common.fields[q].operation_status = bbtc_vv_compare_long_double(
            out->expected[q], out->observed[q], &policy, &comparison);

        if (out->common.fields[q].operation_status == BBTC_VV_STATUS_SUCCESS)
            out->common.fields[q].finding = comparison.finding;
    }
}

/**
 * @brief Run and account for every required mathematical comparison.
 *
 * @details
 * A regression cannot become green by omitting a native family, a case,
 * or a derivative. The final count must be exactly four cases times three
 * native scalar families times three numerical outputs. Any missing or
 * unexpected status/finding fails the cmocka test before the final count.
 *
 * @param state Unused cmocka test state.
 */
static void test_complete_reference_matrix(void** state)
{
    (void)state;

    const bool profile_screened = screen_native_profile();
    size_t completed_cases = 0u;
    size_t completed_fields = 0u;

    /* An unsupported environment must never generate a green test result. */
    assert_true(profile_screened);

    for (size_t i = 0u; i < BBTC_VV_REFERENCE_CASES; ++i)
    {
        bbtc_vv_reference_evidence_float_t result_float = {0};
        bbtc_vv_reference_evidence_double_t result_double = {0};
        bbtc_vv_reference_evidence_long_double_t result_long_double = {0};

        run_reference_float(i, profile_screened, &result_float);
        assert_int_equal(result_float.common.precision, BBTC_PRECISION_FLOAT);
        assert_string_equal(result_float.common.id, s_case_metadata[i].id);
        completed_fields += check_complete_evidence(&result_float.common);
        ++completed_cases;

        run_reference_double(i, profile_screened, &result_double);
        assert_int_equal(result_double.common.precision, BBTC_PRECISION_DOUBLE);
        assert_string_equal(result_double.common.id, s_case_metadata[i].id);
        completed_fields += check_complete_evidence(&result_double.common);
        ++completed_cases;

        run_reference_long_double(i, profile_screened, &result_long_double);
        assert_int_equal(result_long_double.common.precision, BBTC_PRECISION_LONG_DOUBLE);
        assert_string_equal(result_long_double.common.id, s_case_metadata[i].id);
        completed_fields += check_complete_evidence(&result_long_double.common);
        ++completed_cases;
    }

    /* A 36/36 result counts mathematical comparisons, not scientific approval. */
    assert_int_equal(completed_cases, BBTC_VV_REFERENCE_CASES * 3u);
    assert_int_equal(completed_fields,
                     BBTC_VV_REFERENCE_CASES * BBTC_VV_REFERENCE_QUANTITIES * 3u);
}

/**
 * @brief Exercise metadata rejection without invoking production or B1.
 *
 * @details
 * Full adversarial reference integrity and negative-comparator controls are
 * intentionally a distinct B2b.3b checkpoint; this narrow test protects
 * against a missing required ID or inconsistent case identity in B2b.3a.
 *
 * @param state Unused cmocka test state.
 */
static void test_case_metadata_basics(void** state)
{
    (void)state;

    const bbtc_vv_case_metadata_t wrong =
    {
        .id = "M-04",
        .revision = 1u,
        .required = true,
        .category = BBTC_VV_REFERENCE_CATEGORY_MATHEMATICAL,
        .coefficient_count = 3u
    };

    assert_false(validate_case_metadata(0u, NULL));
    assert_false(validate_case_metadata(BBTC_VV_REFERENCE_CASES, &s_case_metadata[0]));
    assert_false(validate_case_metadata(0u, &wrong));

    for (size_t i = 0u; i < BBTC_VV_REFERENCE_CASES; ++i)
        assert_true(validate_case_metadata(i, &s_case_metadata[i]));
}

/**
 * @brief Execute isolated developer-only cmocka tests.
 * @return Conventional nonzero process exit code when any test fails.
 */
int main(void)
{
    const struct CMUnitTest tests[] =
    {
        cmocka_unit_test(test_case_metadata_basics),
        cmocka_unit_test(test_complete_reference_matrix)
    };

    return cmocka_run_group_tests(tests, NULL, NULL);
}
