/**
 * @brief Reject missing or inconsistent identity, category, or bounded count.
 *
 * @details
 * Each fixture below points at a known, static coefficient allocation.
 * The known count is verified before it is passed to production; a count
 * alone cannot establish the readable length of an arbitrary caller pointer.
 * This is a foundation for, not a replacement for, B2b.3b adversarial tests.
 *
 * @param index Canonical 0-based reference-case index.
 * @param metadata Identity presented by the typed fixture.
 * @return true only when the complete required metadata matches the contract.
 */
static bool validate_case_metadata(size_t index, const bbtc_vv_case_metadata_t* metadata)
{
    if (metadata == NULL || index >= BBTC_VV_REFERENCE_CASES)
        return false;

    const bbtc_vv_case_metadata_t* accepted = &s_case_metadata[index];
    return metadata->id != NULL && accepted->id != NULL &&
           strcmp(metadata->id, accepted->id) == 0 &&
           metadata->revision == accepted->revision &&
           metadata->required == accepted->required &&
           metadata->category == BBTC_VV_REFERENCE_CATEGORY_MATHEMATICAL &&
           metadata->coefficient_count == accepted->coefficient_count;
}

/**
 * @brief Validate a fixture's *supplied* quantity and SI-unit declarations.
 *
 * @details
 * A numerical value is inadmissible unless the fixture identifies the exact
 * quantity and its SI unit. Comparing bare numbers and attaching canonical
 * units only after comparison would let a wrongly labelled reference pass.
 *
 * Callers supply exactly BBTC_VV_REFERENCE_QUANTITIES readable records. In
 * this fixed in-process fixture suite, all arrays are statically sized; a
 * pointer alone cannot establish the length of arbitrary external storage.
 * The future interchange/parser design must validate external allocation
 * extents before it calls a routine with this contract.
 *
 * @param quantities Readable, ordered fixture-owned quantity/unit declarations.
 * @return true if and only if every slot matches the accepted SI identity.
 */
static bool validate_quantity_metadata(const bbtc_vv_quantity_metadata_t* quantities)
{
    if (quantities == NULL)
        return false;

    for (size_t q = 0u; q < BBTC_VV_REFERENCE_QUANTITIES; ++q)
    {
        if (quantities[q].quantity != s_quantity_metadata[q].quantity ||
            quantities[q].unit != s_quantity_metadata[q].unit)
        {
            return false;
        }
    }

    return true;
}

/**
 * @brief Recognize each required case/native-family pair exactly once.
 *
 * @details
 * An aggregate count can be forged accidentally by repeating one case while
 * omitting another. This bitmap records all twelve distinct combinations;
 * duplicates and unknown identifiers are refused before changing the mask.
 * The bitmap represents only bounded in-process evidence, not a serialized
 * public report or an acceptance decision.
 *
 * @param index Canonical M-01 through M-04 index (zero based).
 * @param precision Native family recorded by the evidence.
 * @param seen_mask Caller-owned coverage bitmap, updated only on success.
 * @return true if the pair was required and had not previously been recorded.
 */
static bool record_required_case(
    size_t index,
    bbtc_precision_e precision,
    uint16_t* seen_mask
)
{
    if (seen_mask == NULL || index >= BBTC_VV_REFERENCE_CASES)
        return false;

    if (precision != BBTC_PRECISION_FLOAT &&
        precision != BBTC_PRECISION_DOUBLE &&
        precision != BBTC_PRECISION_LONG_DOUBLE)
    {
        return false;
    }

    const unsigned bit_index = (unsigned)(index * 3u + ((unsigned)precision - 1u));
    const uint16_t bit = (uint16_t)(1u << bit_index);

    if ((*seen_mask & bit) != 0u)
        return false;

    *seen_mask = (uint16_t)(*seen_mask | bit);
    return true;
}

/**
 * @brief Validate both distinct required-case coverage and numerical counts.
 *
 * @param seen_mask Bitmap of actual accepted case/family pairs.
 * @param case_count Number of completed case/family records.
 * @param field_count Number of successful B1 numerical comparison decisions.
 * @return true only when all twelve pairs and all 36 fields are present.
 */
static bool required_matrix_complete(
    uint16_t seen_mask,
    size_t case_count,
    size_t field_count
)
{
    return seen_mask == UINT16_C(0x0FFF) &&
           case_count == BBTC_VV_REFERENCE_CASES * 3u &&
           field_count == BBTC_VV_REFERENCE_CASES * BBTC_VV_REFERENCE_QUANTITIES * 3u;
}

/**
 * @brief Delegate baseline ABI/fenv screening to the shared B2b.3c.2 module.
 *
 * @details
 * The shared profile screen compares the caller compiler metadata with the
 * linked production-library metadata and checks nearest rounding. It cannot
 * certify the producer object compilation or its generated instructions. A
 * failing screen forbids mathematical comparison, without silently skipping
 * the required matrix; successful screening is still UNQUALIFIED.
 *
 * @return true when basic host and production scalar identities are coherent.
 */
static bool screen_native_profile(void)
{
    bbtc_vv_virial_profile_observation_t observation = {0};
    bbtc_vv_virial_profile_result_t result = {0};

    /* A positive screen does NOT certify producer compiler flags or runtime ABI. */
    return bbtc_vv_virial_profile_screen(&observation, &result) ==
               BBTC_VV_VIRIAL_PROFILE_SCREENED_UNQUALIFIED &&
           result.issue_mask == BBTC_VV_VIRIAL_ISSUE_NONE;
}

/**
 * @brief Assert the independent outcome axes and return compared-field count.
 *
 * @param evidence Case outcome and its three independently compared quantities.
 * @return Count of comparisons that were actually invoked and completed.
 */
static size_t check_complete_evidence(const bbtc_vv_case_evidence_t* evidence)
{
    size_t compared = 0u;
    assert_non_null(evidence);
    assert_non_null(evidence->id);
    assert_true(evidence->required);
    assert_int_equal(evidence->category, BBTC_VV_REFERENCE_CATEGORY_MATHEMATICAL);
    assert_int_equal(evidence->integrity, BBTC_VV_REFERENCE_INTEGRITY_ACCEPTED);
    assert_int_equal(evidence->profile, BBTC_VV_REFERENCE_PROFILE_SCREENED_UNQUALIFIED);
    assert_true(evidence->producer_called);
    assert_int_equal(evidence->producer_status, BBTC_STATUS_SUCCESS);
    assert_true(evidence->observation_valid);

    for (size_t q = 0u; q < BBTC_VV_REFERENCE_QUANTITIES; ++q)
    {
        const bbtc_vv_field_evidence_t* field = &evidence->fields[q];
        assert_int_equal(field->quantity, s_quantity_metadata[q].quantity);
        assert_int_equal(field->unit, s_quantity_metadata[q].unit);
        assert_int_equal(field->method, BBTC_VV_COMPARISON_EXACT);
        assert_true(field->attempted);
        assert_int_equal(field->operation_status, BBTC_VV_STATUS_SUCCESS);
        assert_int_equal(field->finding, BBTC_VV_FINDING_PASS);
        ++compared;
    }

    return compared;
}
